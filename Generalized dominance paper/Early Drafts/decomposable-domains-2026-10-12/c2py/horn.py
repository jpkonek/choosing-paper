"""Enumerate implication clauses S => h (|S|<=2) and sure-loss pairs among signed gambles SF.
h in posi(S) + R^3_{>=0}:  exists lam>=0 (not all 0) with h - sum lam_a a >= 0.
By Caratheodory in R^3 (cone generated by S and e_1,e_2,e_3), every minimal implication has |S|<=3;
triples are left to the lazy LP check in dcf.py."""
import numpy as np


def single_implies(SF, tol=1e-12):
    n = len(SF)
    I = np.zeros((n, n), bool)
    for ai, a in enumerate(SF):
        H = SF
        with np.errstate(divide='ignore', invalid='ignore'):
            r = H / a
        up = np.where(a > 0, r, np.inf).min(1)
        lo = np.where(a < 0, r, -np.inf).max(1)
        lo = np.maximum(lo, 0)
        I[ai] = (up > lo + tol) | ((up >= lo) & (up > tol))
        I[ai, ai] = False
    return I


def pair_implies(SF, a, b, tol=1e-12):
    H = SF
    n = len(H)
    Acon = [(a[i], b[i]) for i in range(3)] + [(-1, 0), (0, -1)]
    feas = np.zeros(n, bool)
    for i in range(5):
        for j in range(i + 1, 5):
            M = np.array([Acon[i], Acon[j]], float)
            if abs(np.linalg.det(M)) < 1e-14:
                continue
            rhs = np.zeros((n, 2))
            for k, idx in enumerate((i, j)):
                rhs[:, k] = H[:, idx] if idx < 3 else 0
            P = np.linalg.solve(M, rhs.T).T
            ok = (P >= -tol).all(1)
            for i2 in range(3):
                ok &= (P[:, 0] * a[i2] + P[:, 1] * b[i2] <= H[:, i2] + 1e-12)
            ok &= (P.sum(1) > tol)
            feas |= ok
    return feas


def sure_loss_pair(a, b):
    """exists t>0 with t a + b <= 0 (then a,b jointly incur sure loss)"""
    with np.errstate(divide='ignore', invalid='ignore'):
        r = -b / a
    up = np.where(a > 0, r, np.inf).min()
    lo = np.where(a < 0, r, -np.inf).max()
    lo = max(lo, 0)
    if np.any((a == 0) & (b > 0)):
        return False
    return up >= lo and up > 0


def clauses(SF):
    n = len(SF)
    I = single_implies(SF)
    cl = []
    for a in range(n):
        for h in np.where(I[a])[0]:
            cl.append(((a,), (int(h),)))
    for a in range(n):
        for b in range(a + 1, n):
            f = pair_implies(SF, SF[a], SF[b])
            f &= ~I[a]
            f &= ~I[b]
            f[a] = False
            f[b] = False
            for h in np.where(f)[0]:
                cl.append(((a, b), (int(h),)))
            if sure_loss_pair(SF[a], SF[b]):
                cl.append(((a, b), ()))
    return cl
